        m_key = "L_" + nfacts + "_" + nlevels;
        if (!m_designs.ContainsKey(m_key))
        {
            AppException.Raise("design not available");
        }
    }

    public Taguchi(int nfacts1, int nlevels1, int nfacts2, int nlevels2)
    {
        init();
        m_nfacts = nfacts1 + nfacts2;
        string text = "_" + nfacts1 + "_" + nlevels1;
        string text2 = "_" + nfacts2 + "_" + nlevels2;
        if (m_designs.ContainsKey("L" + text + text2))
        {
            m_key = "L" + text + text2;
        }
        else if (m_designs.ContainsKey("L" + text2 + text))
        {
            m_key = "L" + text2 + text;
        }
        else
        {
            AppException.Raise("design not available");
        }
    }

    internal override double[,] getDesignMatrix()
    {
