using System.Text.RegularExpressions;

namespace Quire.Tools.MirrorGen;

/// <summary>What a Mathcad type becomes in Quire.</summary>
public enum Disposition
{
    Mirror,          // in scope: generated (or hand-written) under its Quire name
    Duplicate,       // a copy of a shared native-header type mirrored elsewhere
    Toolchain,       // C++ compiler/runtime artefact: no Quire counterpart
    Dependency,      // provided by a package under its own name (e.g. JetBrains.Annotations)
    OwnEquivalent,   // third-party code replaced by a hand-written Quire equivalent
    Generated,       // regenerated by the .NET SDK
    SharedSource,    // an internal type compiled into many assemblies from one source file
    Deferred,        // licensing or COM interop
}

public sealed record ScopeEntry(string Assembly, string MathcadType, string Kind, string QuireType, Disposition Disposition, int? Phase);

/// <summary>
/// The mirroring rules: which Mathcad types are in scope (from the reviewed docs/mirror/type-map.csv), how names map,
/// and which Quire project each Mathcad assembly lands in.
/// </summary>
public sealed class Rules
{
    public Dictionary<(string Asm, string Type), ScopeEntry> Scope { get; } = new(new ScopeKeyComparer());

    public bool TryFind(string asm, string type, out ScopeEntry entry) => Scope.TryGetValue((asm, type), out entry!);

    /// <summary>Assembly names compare case-insensitively: file names and assembly names differ in case.</summary>
    private sealed class ScopeKeyComparer : IEqualityComparer<(string Asm, string Type)>
    {
        public bool Equals((string Asm, string Type) x, (string Asm, string Type) y) =>
            string.Equals(x.Asm, y.Asm, StringComparison.OrdinalIgnoreCase) && x.Type == y.Type;
        public int GetHashCode((string Asm, string Type) k) =>
            HashCode.Combine(StringComparer.OrdinalIgnoreCase.GetHashCode(k.Asm), k.Type);
    }

    public static Rules Load(string typeMapCsv)
    {
        var rules = new Rules();
        foreach (var line in File.ReadLines(typeMapCsv).Skip(1))
        {
            var f = SplitCsv(line);
            string asm = Path.GetFileNameWithoutExtension(f[0]);
            string status = f[5];
            var disposition = status switch
            {
                "missing" or "exists" or "exists-elsewhere" => Disposition.Mirror,
                "c++ artefact" => Disposition.Toolchain,
                _ when status.StartsWith("duplicate") => Disposition.Duplicate,
                _ when status.StartsWith("dependency") => Disposition.Dependency,
                _ when status.StartsWith("third-party") => Disposition.OwnEquivalent,
                _ when status.StartsWith("generated") => Disposition.Generated,
                _ when status.StartsWith("shared source") => Disposition.SharedSource,
                _ when status.StartsWith("deferred") => Disposition.Deferred,
                _ => throw new InvalidDataException($"unknown status '{status}'"),
            };
            int? phase = int.TryParse(f[6], out var p) ? p : null;
            rules.Scope[(asm, f[1])] = new ScopeEntry(asm, f[1], f[2], MapTypeName(f[1], asm), disposition, phase);
        }
        return rules;
    }

    /// <summary>Mathcad assemblies that are deferred wholesale and so not listed type by type in the type map.</summary>
    public static bool IsDeferredAssembly(string asm) =>
        asm is "LicenseWizard" or "Ptc.License.Plpf" or "Ptc.OleInterop" || asm.StartsWith("interop.", StringComparison.OrdinalIgnoreCase);

    // ---------------------------------------------------------------- names

    private static readonly (Regex From, string To)[] NamespaceRules =
    [
        (new(@"^System\.Reflection\.Emit\.PTC\.Mathcad\.Mpl(?=\.|$)"), "System.Reflection.Emit.Quire.Mpl"), // D8
        (new(@"^Ptc\.MathcadPrime(?=\.|$)"), "Quire"),
        (new(@"^Ptc(?=\.|$)"), "Quire"),
        (new(@"^Spirit(?=\.|$)"), "Quire"),
        (new(@"^Mathcad(?=\.|$)"), "Quire"),
        (new(@"^Mathsoft(?=\.|$)"), "Quire"),
        (new(@"^MathcadAutomationPrivate(?=\.|$)"), "Quire.AutomationPrivate"),
    ];

    /// <summary>Maps a Mathcad namespace to its Quire namespace. Global-namespace types go to Quire.Native.&lt;Assembly&gt;.</summary>
    public static string MapNamespace(string ns, string asm)
    {
        if (ns.Length == 0) return "Quire.Native." + NativeAssemblyName(asm);
        foreach (var (from, to) in NamespaceRules)
            if (from.IsMatch(ns)) return from.Replace(ns, to, 1);
        return "Quire." + ns; // Mpl, Mcd (D1), Engine, Efi, Hex, mslisp, ...
    }

    /// <summary>Maps a full metadata type name (nested types joined by '+').</summary>
    public static string MapTypeName(string fullName, string asm)
    {
        string outer = fullName.Split('+')[0];
        int dot = OuterNamespaceSplit(outer);
        string ns = dot < 0 ? "" : outer[..dot];
        string rest = dot < 0 ? fullName : fullName[(dot + 1)..];
        return MapNamespace(ns, asm) + "." + rest;
    }

    /// <summary>The namespace/name split point, ignoring dots inside C++ template arguments.</summary>
    private static int OuterNamespaceSplit(string name)
    {
        int depth = 0, last = -1;
        for (int i = 0; i < name.Length; i++)
        {
            char c = name[i];
            if (c == '<') depth++;
            else if (c == '>') depth--;
            else if (c == '.' && depth == 0) last = i;
        }
        return last;
    }

    /// <summary>e.g. efiio_ → EfiioImpl, mcfront12 → Mcfront12, engutils-mgd → EngutilsMgd.</summary>
    public static string NativeAssemblyName(string asm)
    {
        var parts = asm.Split(['-', '.'], StringSplitOptions.RemoveEmptyEntries);
        string s = string.Concat(parts.Select(p => char.ToUpperInvariant(p[0]) + p[1..]));
        return s.EndsWith('_') ? s.TrimEnd('_') + "Impl" : s;
    }

    // ---------------------------------------------------------------- projects (D2)

    /// <summary>The Quire project that hosts a Mathcad assembly's types.</summary>
    public static string ProjectFor(string asm) => asm.ToLowerInvariant() switch
    {
        "mathcadprime" => "Quire",
        "ptc.mathcadprime.automation" => "Quire.Automation",
        "ptc.engnotebook.automation" => "Quire.EngNotebook.Automation",
        "ptc.engnotebookplus.automation" => "Quire.EngNotebookPlus.Automation",
        var a when a.StartsWith("ptc.") => "Quire." + asm[4..],
        // D2: consolidated, following the layers of Mathcad's own assembly graph so the projects stay acyclic.
        "mplasb" => "Quire.Mpl.Emit",
        "mplrun" => "Quire.Mpl",
        var a when a.StartsWith("mpl") || a is "hashtable" or "mcdrun" || a.StartsWith("mcdstaticunitsystem") => "Quire.Mpl.Modules",
        "utilsmgd" => "Quire.Utils",
        "utl-mgd" or "mcmisc" => "Quire.Engine.Utl",
        var a when a.StartsWith("efi") => "Quire.Efi",
        "automation" or "automationmgd" or "componentsmgd" => "Quire.Automation.Native",
        "iengine" or "engutils-mgd" => "Quire.Engine",
        var a when a.StartsWith("mcd") => "Quire.Mcd",
        "mccore12" or "mceng" or "mcfront12" or "msclr" or "msgen" or "mslisp" or "mspcons-mgd" => "Quire.Engine.Native",
        _ => throw new ArgumentException($"no project rule for {asm}"),
    };

    public static string[] SplitCsv(string line)
    {
        var fields = new List<string>();
        var sb = new System.Text.StringBuilder();
        bool quoted = false;
        for (int i = 0; i < line.Length; i++)
        {
            char c = line[i];
            if (quoted)
            {
                if (c == '"' && i + 1 < line.Length && line[i + 1] == '"') { sb.Append('"'); i++; }
                else if (c == '"') quoted = false;
                else sb.Append(c);
            }
            else if (c == '"') quoted = true;
            else if (c == ',') { fields.Add(sb.ToString()); sb.Clear(); }
            else sb.Append(c);
        }
        fields.Add(sb.ToString());
        return [.. fields];
    }
}
