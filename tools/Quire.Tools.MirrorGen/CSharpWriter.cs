using System.Collections.Immutable;
using System.Globalization;
using System.Text;

namespace Quire.Tools.MirrorGen;

/// <summary>Renders planned types as C# partial declarations whose members are stubs.</summary>
public sealed class CSharpWriter(Mapper mapper, Planner plan)
{
    private const string Throw = "throw global::Quire.Mirror.MirrorStub.NotImplemented()";
    private const string StubAttr = "[global::Quire.Mirror.MirrorStub]";

    private readonly Dictionary<(string, string), List<TypeModel>> _nested = mapper.Types
        .Where(t => t.DeclaringType != null)
        .GroupBy(t => (t.Project!, t.DeclaringType!))
        .ToDictionary(g => g.Key, g => g.ToList());

    private sealed record Ctx(ImmutableArray<string> TypeParams, ImmutableArray<string> MethodParams)
    {
        public Ctx WithMethod(MethodModel m) => this with { MethodParams = [.. m.GenericParams.Select(g => Identifier.Source(g.Name))] };
    }

    /// <summary>The whole file for a top-level type, or null if nothing is generated for it.</summary>
    public string? File(TypeModel t)
    {
        if (plan.TypeSkip.ContainsKey(t)) return null;
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"// Mirror of {t.MirrorOf}.");
        sb.AppendLine("// Generated by Quire.Tools.MirrorGen from assembly metadata. Do not edit: write members in a separate partial");
        sb.AppendLine("// declaration and regenerate, and the generator leaves them out of this file.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable disable");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine();
        sb.AppendLine($"namespace {t.Namespace};");
        sb.AppendLine();
        WriteType(sb, t, 0);
        return sb.ToString();
    }

    // ------------------------------------------------------------------ types

    private void WriteType(StringBuilder sb, TypeModel t, int indent)
    {
        string pad = new(' ', indent * 4);
        if (plan.TypeSkip.ContainsKey(t)) return;
        var all = t.GenericParams.Select(g => Identifier.Source(g.Name)).ToImmutableArray();
        int outer = OuterArity(t);
        var ctx = new Ctx(all, []);
        var own = t.GenericParams.Skip(outer).ToList();
        string name = Identifier.Source(t.Name);
        string typeParams = own.Count == 0 ? "" : "<" + string.Join(", ", own.Select(g =>
            (t.Kind is TypeKind.Interface or TypeKind.Delegate ? g.Variance switch { 1 => "out ", -1 => "in ", _ => "" } : "") + Identifier.Source(g.Name))) + ">";
        string access = AccessText(TypeAccess(t));

        sb.AppendLine($"{pad}[global::Quire.Mirror.MirrorOf(\"{t.MirrorOf}\")]");
        if (t.IsFlags) sb.AppendLine($"{pad}[global::System.Flags]");

        if (t.Kind == TypeKind.Enum)
        {
            string underlying = t.EnumUnderlying is null or "System.Int32" ? "" : " : " + Keyword(t.EnumUnderlying);
            sb.AppendLine($"{pad}{access} enum {name}{underlying}");
            sb.AppendLine($"{pad}{{");
            foreach (var f in t.Fields.Where(f => f.Const))
                sb.AppendLine($"{pad}    {Identifier.Source(f.Name)} = {NumberLiteral(f.Value)},");
            sb.AppendLine($"{pad}}}");
            return;
        }
        if (t.Kind == TypeKind.Delegate)
        {
            var invoke = t.Methods.FirstOrDefault();
            if (invoke == null) { t.Notes.Add("delegate without a mappable Invoke; not generated"); return; }
            var mctx = ctx.WithMethod(invoke);
            string sig = $"{RefReturn(invoke.Return, ctx)} {name}{typeParams}({Params(invoke, ctx, t)}){Constraints(own, ctx, pad)};";
            sb.AppendLine($"{pad}{access} {(Unsafe(invoke) ? "unsafe " : "")}delegate {sig}");
            return;
        }

        if (t.NativeSize is > 0)
            sb.AppendLine($"{pad}[global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Sequential, Size = {t.NativeSize})]");
        var mods = new List<string> { access };
        if (t.Kind == TypeKind.Class)
        {
            if (t.IsStatic) mods.Add("static");
            else if (t.Abstract) mods.Add("abstract");
            else if (t.Sealed) mods.Add("sealed");
        }
        if (t.Kind == TypeKind.Struct && t.IsReadOnly) mods.Add("readonly");
        if (t.Kind == TypeKind.Struct && t.IsByRefLike) mods.Add("ref");
        mods.Add("partial");
        mods.Add(t.Kind switch
        {
            TypeKind.Struct => plan.IsRecord(t) ? "record struct" : "struct",
            TypeKind.Interface => "interface",
            _ => plan.IsRecord(t) ? "record" : "class",
        });

        var bases = new List<string>();
        if (t.Kind == TypeKind.Class && t.BaseType is NamedSig b && b.Name != "System.Object" && !plan.DropBase.Contains(t))
            bases.Add(T(b, ctx));
        bases.AddRange(t.Interfaces.Select(i => T(i, ctx)).Distinct());
        sb.AppendLine($"{pad}{string.Join(" ", mods)} {name}{typeParams}{(bases.Count > 0 ? " : " + string.Join(", ", bases) : "")}{Constraints(own, ctx, pad + "    ")}");
        sb.AppendLine($"{pad}{{");
        WriteMembers(sb, t, ctx, pad + "    ");
        if (_nested.TryGetValue((t.Project!, t.FullName), out var nested))
            foreach (var n in nested)
            {
                sb.AppendLine();
                WriteType(sb, n, indent + 1);
            }
        sb.AppendLine($"{pad}}}");
    }

    private int OuterArity(TypeModel t) =>
        t.DeclaringType != null && mapper.Resolve(t.DeclaringType, t.Project) is { } parent ? parent.GenericParams.Length : 0;

    /// <summary>A type's declared access, lowered when its base type is less accessible than it.</summary>
    private static Access TypeAccess(TypeModel t) => t.Access; // the planner has already lowered it where needed

    private string Constraints(IEnumerable<GenericParam> gps, Ctx ctx, string pad)
    {
        var sb = new StringBuilder();
        foreach (var g in gps)
        {
            var parts = new List<string>();
            if (g.Struct) parts.Add("struct");
            else if (g.Class) parts.Add("class");
            parts.AddRange(g.Constraints.Select(c => T(c, ctx)));
            if (g.New) parts.Add("new()");
            if (parts.Count > 0) sb.Append($" where {Identifier.Source(g.Name)} : {string.Join(", ", parts)}");
        }
        return sb.ToString();
    }

    // ------------------------------------------------------------------ members

    private void WriteMembers(StringBuilder sb, TypeModel t, Ctx ctx, string pad)
    {
        // C# names: fields, properties, events and nested types each need a unique name, distinct from methods and
        // from the type's own name. Obfuscated Mathcad types reuse names across kinds; a clashing member is renamed
        // with a trailing underscore when nothing binds to it by name (not virtual, no interface), else skipped.
        string Plain(string n) => n.Split('`')[0];
        var methodNames = t.Methods.Where(m => !plan.Skip.Contains(m)).Select(m => plan.Renames.GetValueOrDefault(m, m.Name)).ToHashSet();
        var taken = new HashSet<string> { Plain(t.Name) };
        if (_nested.TryGetValue((t.Project!, t.FullName), out var nn)) foreach (var n in nn) taken.Add(Plain(n.Name));
        string Unique(string name)
        {
            string n = name + "_";
            while (taken.Contains(n) || methodNames.Contains(n)) n += "_";
            return n;
        }
        string? Claim(string name, bool renamable, string what, bool isMethod = false)
        {
            if (name.Contains('.')) return name; // explicit implementations don't occupy a name
            bool clash = taken.Contains(Plain(name)) || (!isMethod && methodNames.Contains(name));
            if (!clash) { if (!isMethod) taken.Add(Plain(name)); return name; }
            if (!renamable) { t.Notes.Add($"skipped {what} {name}: name clash"); return null; }
            string renamed = Unique(name);
            if (!isMethod) taken.Add(renamed);
            t.Notes.Add($"renamed {what} {name} to {renamed}: name clash");
            return renamed;
        }

        foreach (var f in t.Fields.Where(f => !plan.Skip.Contains(f)))
            if (Claim(f.Name, true, "field") is { } name) WriteField(sb, t, f, ctx, pad, name);

        string? indexerName = null;
        foreach (var p in t.Properties.Where(p => !plan.Skip.Contains(p)))
        {
            var lead = p.Getter ?? p.Setter!;
            string? name = p.Name;
            if (p.Index.Length > 0 && !p.Name.Contains('.'))
            {
                indexerName ??= p.Name;
                if (p.Name != indexerName) { t.Notes.Add($"skipped indexed property {p.Name}: C# allows one indexer name per type"); continue; }
            }
            else name = Claim(p.Name, !lead.Virtual, "property");
            if (name != null) WriteProperty(sb, t, p, ctx, pad, name);
        }

        foreach (var e in t.Events.Where(e => !plan.Skip.Contains(e)))
            if (Claim(e.Name, !e.Adder!.Virtual, "event") is { } name) WriteEvent(sb, t, e, ctx, pad, name);

        var signatures = new HashSet<string>();
        foreach (var m in t.Methods.Where(m => !plan.Skip.Contains(m)))
        {
            string original = plan.Renames.GetValueOrDefault(m, m.Name);
            string? name = m.IsConstructor || IsExplicit(m) ? m.Name : Claim(original, !m.Virtual, "method", isMethod: true);
            if (name == null) continue;
            string key = $"{name}`{m.GenericParams.Length}({string.Join(",", m.Params.Select(p => p.Type is ByRefSig r ? r.Element : p.Type))})";
            if (!IsExplicit(m) && !signatures.Add(key)) { t.Notes.Add($"skipped overload {key}: differs only by modifiers C# can't express"); continue; }
            WriteMethod(sb, t, m, ctx, pad, name);
        }

        if (plan.ExtraExplicit.TryGetValue(t, out var extra))
            WriteExtraExplicit(sb, t, extra, ctx, pad);
    }

    private void WriteField(StringBuilder sb, TypeModel t, FieldModel f, Ctx ctx, string pad, string memberName)
    {
        string type = T(f.Type, ctx);
        string access = MemberAccess(t, f.Access, [f.Type], $"field {f.Name}");
        string unsafeMod = HasPointer(f.Type) ? "unsafe " : "";
        string name = Identifier.Source(memberName);
        sb.AppendLine($"{pad}{StubAttr}");
        if (f.Const)
            sb.AppendLine($"{pad}{access} const {type} {name} = {Literal(f.Value, f.Type, ctx)};");
        else
        {
            bool ro = f.ReadOnly || (t.Kind == TypeKind.Struct && t.IsReadOnly && !f.Static);
            sb.AppendLine($"{pad}{access} {(f.Static ? "static " : "")}{(ro ? "readonly " : "")}{unsafeMod}{type} {name};");
        }
    }

    private bool IsExplicit(MethodModel m) =>
        m.Access == Access.Private && !m.Implements.IsEmpty && !plan.Renames.ContainsKey(m)
        && plan.Modifiers.GetValueOrDefault(m) is not (Modifier.Override or Modifier.SealedOverride or Modifier.AbstractOverride);

    private void WriteMethod(StringBuilder sb, TypeModel t, MethodModel m, Ctx typeCtx, string pad, string memberName)
    {
        var ctx = typeCtx.WithMethod(m);
        string unsafeMod = Unsafe(m) ? "unsafe " : "";
        string typeName = Identifier.Source(t.Name);
        string generics = m.GenericParams.Length == 0 ? "" : "<" + string.Join(", ", m.GenericParams.Select(g => Identifier.Source(g.Name))) + ">";

        if (IsExplicit(m))
        {
            foreach (var (iface, name) in m.Implements.Where(i => plan.IsInterface(i.Interface, t.Project!)))
            {
                string explicitBody = IsDispose(m with { Name = name }) ? " { }" : $" => {Throw};";
                sb.AppendLine($"{pad}{StubAttr}");
                sb.AppendLine($"{pad}{unsafeMod}{RefReturn(m.Return, ctx)} {T(iface, ctx)}.{Identifier.Source(name)}{generics}({Params(m, ctx, t, explicitImpl: true)}){explicitBody}");
            }
            return;
        }

        if (m.Name == ".ctor")
        {
            if (t.Kind == TypeKind.Interface || t.IsStatic) return;
            string access = MemberAccess(t, m.Access, m.Params.Select(p => p.Type), "constructor");
            // With a hand-written part, chain to its constructor so the hand-written initialisation runs.
            var hand = plan.HandConstructor(t);
            var call = hand == null && t.Kind == TypeKind.Class ? plan.BaseCallFor(t) : null;
            string init = hand != null
                ? " : this(" + string.Join(", ", hand.Params.Where(p => !p.HasDefault).Select(p => $"default({T(p.Type, ctx)})")) + ")"
                : call == null ? "" : " : base(" + string.Join(", ", call.Args.Select(a => $"default({T(a, ctx)})")) + ")";
            bool unsafeCtor = Unsafe(m) || (call?.Args.Any(HasPointer) ?? false);
            // Stub constructors succeed (only out parameters are assigned): objects can still be created, by
            // hand-written subclasses or by WPF, and their unimplemented members throw when used.
            string outs = string.Concat(m.Params.Where(p => p.Out).Select(p => $" {Identifier.Source(p.Name)} = default;"));
            sb.AppendLine($"{pad}{StubAttr}");
            sb.AppendLine($"{pad}{access} {(unsafeCtor ? "unsafe " : "")}{typeName}({Params(m, ctx, t)}){init} {{{outs} }}");
            return;
        }

        if (m.Name == "Finalize" && m.Params.Length == 0 && m.Virtual && !m.NewSlot && t.Kind == TypeKind.Class)
        {
            sb.AppendLine($"{pad}{StubAttr}");
            sb.AppendLine($"{pad}~{typeName}() {{ }} // stub finalizers must not throw: they also run for objects whose constructor threw");
            return;
        }

        string accessText = InterfaceAware(t, MemberAccess(t, plan.AccessOverrides.GetValueOrDefault(m, m.Access),
            m.Params.Select(p => p.Type).Append(m.Return), $"method {m.Name}", Overriding(m)));
        var modifier = plan.Modifiers.GetValueOrDefault(m);
        if (modifier is Modifier.Abstract or Modifier.AbstractOverride && !t.Abstract && t.Kind != TypeKind.Interface)
        {
            t.Notes.Add($"abstract {m.Name} in a non-abstract type declared virtual");
            modifier = modifier == Modifier.Abstract ? Modifier.Virtual : Modifier.Override;
        }
        string mods = (m.Static ? (t.Kind == TypeKind.Interface && m.Abstract ? "static abstract " : "static ") : "") + ModifierText(modifier, t);
        // Generated interface members get throwing default bodies: hand-written classes that implement a mirrored
        // interface then keep compiling until a phase implements the member for real.
        bool hasBody = !(modifier is Modifier.Abstract or Modifier.AbstractOverride) || t.Kind == TypeKind.Interface && !m.Static;

        if (OperatorSyntax(t, m, ctx) is { } op)
        {
            sb.AppendLine($"{pad}{StubAttr}");
            sb.AppendLine($"{pad}public static {unsafeMod}{op}({Params(m, ctx, t)}) => {Throw};");
            return;
        }

        string constraints = modifier is Modifier.Override or Modifier.SealedOverride or Modifier.AbstractOverride ? "" : Constraints(m.GenericParams, ctx, " ");
        string body = plan.CallsBase.Contains(m) && memberName == m.Name
            ? $" => base.{Identifier.Source(m.Name)}{generics}({Args(m.Params)});"
            : IsDispose(m) ? " { }" : $" => {Throw};";
        sb.AppendLine($"{pad}{StubAttr}");
        sb.AppendLine($"{pad}{accessText}{mods}{unsafeMod}{RefReturn(m.Return, ctx)} {Identifier.Source(memberName)}{generics}({Params(m, ctx, t)}){constraints}{(hasBody ? body : ";")}");

        // Non-private methods that also implement interface members under another name (C++/CLI named overrides).
        foreach (var (iface, name) in m.Implements)
            if (!(m.Access == Access.Public && name == m.Name && !m.Static) && plan.IsInterface(iface, t.Project!))
            {
                sb.AppendLine($"{pad}{StubAttr}");
                sb.AppendLine($"{pad}{unsafeMod}{RefReturn(m.Return, ctx)} {T(iface, ctx)}.{Identifier.Source(name)}{generics}({Params(m, ctx, t, explicitImpl: true)}) => {Throw};");
            }
    }

    private static bool Overriding(MethodModel m) => m.Virtual && !m.NewSlot;

    /// <summary>
    /// Dispose stubs do nothing instead of throwing: using blocks, WPF and generic cleanup call them on objects whose
    /// other members are still stubs.
    /// </summary>
    private static bool IsDispose(MethodModel m) =>
        m.Name.Split('.')[^1] == "Dispose" && m.Return is NamedSig { Name: "System.Void" }
        && (m.Params.Length == 0 || m.Params is [{ Type: NamedSig { Name: "System.Boolean" } }]);

    private void WriteProperty(StringBuilder sb, TypeModel t, PropertyModel p, Ctx ctx, string pad, string memberName)
    {
        var lead = p.Getter ?? p.Setter!;
        string unsafeMod = HasPointer(p.Type) || p.Index.Any(i => HasPointer(i.Type)) ? "unsafe " : "";
        string type = RefReturn(p.Type, ctx);
        bool isIndexer = p.Index.Length > 0;
        string index = isIndexer ? "[" + Params(lead, ctx, t, p.Index) + "]" : "";

        if (p.Name.Contains('.') && lead.Implements.Length > 0)
        {
            var (iface, accessor) = lead.Implements[0];
            string member = isIndexer ? "this" : Identifier.Source(accessor[(accessor.IndexOf('_') + 1)..]);
            sb.AppendLine($"{pad}{StubAttr}");
            sb.AppendLine($"{pad}{unsafeMod}{type} {T(iface, ctx)}.{member}{index} {{ {(p.Getter != null ? $"get => {Throw}; " : "")}{(p.Setter != null ? $"{(p.Setter.InitOnly ? "init" : "set")} => {Throw}; " : "")}}}");
            return;
        }

        var getAccess = p.Getter == null ? (Access?)null : plan.AccessOverrides.GetValueOrDefault(p.Getter, p.Getter.Access);
        var setAccess = p.Setter == null ? (Access?)null : plan.AccessOverrides.GetValueOrDefault(p.Setter, p.Setter.Access);
        var propAccess = getAccess == null ? setAccess!.Value : setAccess == null ? getAccess.Value : Max(getAccess.Value, setAccess.Value);
        var modifier = plan.Modifiers.GetValueOrDefault(lead);
        if (modifier is Modifier.Abstract or Modifier.AbstractOverride && !t.Abstract && t.Kind != TypeKind.Interface)
            modifier = modifier == Modifier.Abstract ? Modifier.Virtual : Modifier.Override;
        bool abstractish = modifier is Modifier.Abstract or Modifier.AbstractOverride && t.Kind != TypeKind.Interface;
        string access = InterfaceAware(t, MemberAccess(t, propAccess, p.Index.Select(i => i.Type).Append(p.Type), $"property {p.Name}", Overriding(lead)));
        string mods = (lead.Static ? "static " : "") + (t.Kind == TypeKind.Interface ? "" : ModifierText(modifier, t));
        string name = isIndexer ? "this" : Identifier.Source(memberName);
        if (isIndexer && p.Name != "Item")
            sb.AppendLine($"{pad}[global::System.Runtime.CompilerServices.IndexerName(\"{p.Name}\")]");

        bool callsBase = plan.CallsBase.Contains(lead) && memberName == p.Name;
        string target = isIndexer ? $"base[{Args(p.Index)}]" : $"base.{Identifier.Source(p.Name)}";
        string Accessor(string kw, Access? a)
        {
            if (a == null) return "";
            string am = a.Value != propAccess && getAccess != null && setAccess != null && t.Kind != TypeKind.Interface ? AccessText(a.Value) + " " : "";
            if (abstractish) return $"{am}{kw}; ";
            string body = !callsBase ? Throw : kw == "get" ? target : $"{target} = value";
            return $"{am}{kw} => {body}; ";
        }
        sb.AppendLine($"{pad}{StubAttr}");
        sb.AppendLine($"{pad}{access}{mods}{unsafeMod}{type} {name}{index} {{ {Accessor("get", getAccess)}{Accessor(p.Setter?.InitOnly == true ? "init" : "set", setAccess)}}}");
    }

    private void WriteEvent(StringBuilder sb, TypeModel t, EventModel e, Ctx ctx, string pad, string memberName)
    {
        var lead = e.Adder!;
        string type = T(e.Type, ctx);
        if (e.Name.Contains('.') && lead.Implements.Length > 0)
        {
            var (iface, accessor) = lead.Implements[0];
            sb.AppendLine($"{pad}{StubAttr}");
            sb.AppendLine($"{pad}event {type} {T(iface, ctx)}.{Identifier.Source(accessor[(accessor.IndexOf('_') + 1)..])} {{ add {{ }} remove {{ }} }}");
            return;
        }
        var modifier = plan.Modifiers.GetValueOrDefault(lead);
        if (modifier is Modifier.Abstract or Modifier.AbstractOverride && !t.Abstract && t.Kind != TypeKind.Interface)
            modifier = modifier == Modifier.Abstract ? Modifier.Virtual : Modifier.Override;
        bool abstractish = modifier is Modifier.Abstract or Modifier.AbstractOverride && t.Kind != TypeKind.Interface;
        string access = InterfaceAware(t, MemberAccess(t, plan.AccessOverrides.GetValueOrDefault(lead, lead.Access), [e.Type], $"event {e.Name}", Overriding(lead)));
        string mods = (lead.Static ? "static " : "") + (t.Kind == TypeKind.Interface ? "" : ModifierText(modifier, t));
        sb.AppendLine($"{pad}{StubAttr}");
        bool callsBase = plan.CallsBase.Contains(lead) && memberName == e.Name;
        string evt = $"base.{Identifier.Source(e.Name)}";
        sb.AppendLine(abstractish
            ? $"{pad}{access}{mods}event {type} {Identifier.Source(memberName)};"
            : callsBase
                ? $"{pad}{access}{mods}event {type} {Identifier.Source(memberName)} {{ add => {evt} += value; remove => {evt} -= value; }}"
                // Subscribing must not throw (WPF subscribes to PropertyChanged and the like): field-like events in
                // classes and structs, empty accessors where C# requires accessors.
                : t.Kind == TypeKind.Interface
                    ? $"{pad}{access}{mods}event {type} {Identifier.Source(memberName)} {{ add {{ }} remove {{ }} }}"
                    : $"{pad}{access}{mods}event {type} {Identifier.Source(memberName)};");
    }

    private void WriteExtraExplicit(StringBuilder sb, TypeModel t, List<(TypeSig Interface, MethodModel Member, string Kind, string Name)> extra,
        Ctx ctx, string pad)
    {
        foreach (var group in extra.GroupBy(x => (x.Interface.ToString(), x.Kind, x.Name)))
        {
            var first = group.First();
            string iface = T(first.Interface, ctx);
            sb.AppendLine($"{pad}{StubAttr}");
            switch (first.Kind)
            {
                case "property":
                {
                    var getter = group.FirstOrDefault(x => x.Member.Name.StartsWith("get_")).Member;
                    var setter = group.FirstOrDefault(x => x.Member.Name.StartsWith("set_")).Member;
                    var type = getter?.Return ?? setter!.Params[^1].Type;
                    var index = getter?.Params ?? setter!.Params.RemoveAt(setter.Params.Length - 1);
                    string name = index.Length > 0 ? "this[" + Params(getter ?? setter!, ctx, t, index) + "]" : Identifier.Source(first.Name);
                    sb.AppendLine($"{pad}{RefReturn(type, ctx)} {iface}.{name} {{ {(getter != null ? $"get => {Throw}; " : "")}{(setter != null ? $"set => {Throw}; " : "")}}}");
                    break;
                }
                case "event":
                {
                    var add = group.First().Member;
                    sb.AppendLine($"{pad}event {T(add.Params[0].Type, ctx)} {iface}.{Identifier.Source(first.Name)} {{ add {{ }} remove {{ }} }}");
                    break;
                }
                default:
                {
                    var m = first.Member;
                    var mctx = ctx.WithMethod(m);
                    string generics = m.GenericParams.Length == 0 ? "" : "<" + string.Join(", ", m.GenericParams.Select(g => Identifier.Source(g.Name))) + ">";
                    sb.AppendLine($"{pad}{RefReturn(m.Return, mctx)} {iface}.{Identifier.Source(m.Name)}{generics}({Params(m, mctx, t, explicitImpl: true)}){(IsDispose(m) ? " { }" : $" => {Throw};")}");
                    break;
                }
            }
        }
    }

    // ------------------------------------------------------------------ operators

    private static readonly Dictionary<string, string> Operators = new()
    {
        ["op_UnaryPlus"] = "+", ["op_UnaryNegation"] = "-", ["op_LogicalNot"] = "!", ["op_OnesComplement"] = "~",
        ["op_Increment"] = "++", ["op_Decrement"] = "--", ["op_True"] = "true", ["op_False"] = "false",
        ["op_Addition"] = "+", ["op_Subtraction"] = "-", ["op_Multiply"] = "*", ["op_Division"] = "/", ["op_Modulus"] = "%",
        ["op_BitwiseAnd"] = "&", ["op_BitwiseOr"] = "|", ["op_ExclusiveOr"] = "^", ["op_LeftShift"] = "<<", ["op_RightShift"] = ">>",
        ["op_Equality"] = "==", ["op_Inequality"] = "!=", ["op_LessThan"] = "<", ["op_GreaterThan"] = ">",
        ["op_LessThanOrEqual"] = "<=", ["op_GreaterThanOrEqual"] = ">=",
    };

    private static readonly Dictionary<string, string> Pairs = new()
    {
        ["op_Equality"] = "op_Inequality", ["op_Inequality"] = "op_Equality", ["op_LessThan"] = "op_GreaterThan",
        ["op_GreaterThan"] = "op_LessThan", ["op_LessThanOrEqual"] = "op_GreaterThanOrEqual",
        ["op_GreaterThanOrEqual"] = "op_LessThanOrEqual", ["op_True"] = "op_False", ["op_False"] = "op_True",
    };

    /// <summary>"implicit operator T" / "R operator +" when the method is a valid C# operator, else null (a plain method).</summary>
    private string? OperatorSyntax(TypeModel t, MethodModel m, Ctx ctx)
    {
        if (!m.SpecialName || !m.Static || m.Access != Access.Public || !m.Name.StartsWith("op_")) return null;
        bool Self(TypeSig s) => s is NamedSig n && (n.Name == t.FullName
            || (n.Name == "System.Nullable`1" && n.Args[0] is NamedSig a && a.Name == t.FullName));
        if (m.Name is "op_Implicit" or "op_Explicit")
        {
            if (m.Params.Length != 1 || !(Self(m.Return) ^ Self(m.Params[0].Type))) return null;
            return $"{(m.Name == "op_Implicit" ? "implicit" : "explicit")} operator {T(m.Return, ctx)}";
        }
        if (!Operators.TryGetValue(m.Name, out var symbol) || !m.Params.Any(p => Self(p.Type))) return null;
        bool unary = m.Name is "op_UnaryPlus" or "op_UnaryNegation" or "op_LogicalNot" or "op_OnesComplement" or "op_Increment"
            or "op_Decrement" or "op_True" or "op_False";
        if (m.Params.Length != (unary ? 1 : 2)) return null;
        if (Pairs.TryGetValue(m.Name, out var pair) && !t.Methods.Any(o => o.Name == pair && o.SpecialName && !plan.Skip.Contains(o))) return null;
        return $"{T(m.Return, ctx)} operator {symbol}";
    }

    // ------------------------------------------------------------------ access and modifiers

    private static int Rank(Access a) => a switch
    {
        Access.Private => 0, Access.PrivateProtected => 1, Access.Internal => 2, Access.Protected => 2,
        Access.ProtectedInternal => 3, _ => 4,
    };

    private static Access Max(Access a, Access b) =>
        Rank(a) == Rank(b) && a != b ? Access.ProtectedInternal : Rank(a) >= Rank(b) ? a : b;

    private static string AccessText(Access a) => a switch
    {
        Access.Public => "public", Access.Internal => "internal", Access.Protected => "protected",
        Access.ProtectedInternal => "protected internal", Access.PrivateProtected => "private protected", _ => "private",
    };

    /// <summary>
    /// The access a member is declared with: structs have no protected members, and a member visible outside the
    /// assembly can't expose a non-public type (C++/CLI allows both).
    /// </summary>
    private string MemberAccess(TypeModel t, Access a, IEnumerable<TypeSig> sigs, string what, bool overriding = false)
    {
        if (t.Kind == TypeKind.Struct && a is Access.Protected or Access.PrivateProtected) a = Access.Private;
        if (t.Kind == TypeKind.Struct && a is Access.ProtectedInternal) a = Access.Internal;
        if (!overriding && Rank(a) >= 2 && a != Access.Internal && IsEffectivelyPublic(t) && sigs.Any(s => UsesNonPublic(s, t.Project!)))
        {
            t.Notes.Add($"{what} declared internal: its signature uses a non-public type");
            a = Access.Internal;
        }
        return AccessText(a);
    }

    /// <summary>Interface members are public unless lowered; the modifier is then written out.</summary>
    private static string InterfaceAware(TypeModel t, string access) =>
        t.Kind == TypeKind.Interface && access == "public" ? "" : access + " ";

    private bool IsEffectivelyPublic(TypeModel t) => plan.IsEffectivelyPublic(t);

    private bool UsesNonPublic(TypeSig s, string project) => Stats.Named(s).Any(n =>
        mapper.Resolve(n.Name, project) is { Project: not null } q && q.Project == n.Assembly && !IsEffectivelyPublic(q));

    private static string ModifierText(Modifier m, TypeModel t) => m switch
    {
        Modifier.Virtual when !t.Sealed && t.Kind == TypeKind.Class => "virtual ",
        Modifier.Override => "override ",
        Modifier.SealedOverride => t.Kind == TypeKind.Struct ? "override " : "sealed override ", // structs are sealed
        Modifier.Abstract when t.Kind != TypeKind.Interface => "abstract ",
        Modifier.AbstractOverride => "abstract override ",
        _ => "",
    };

    // ------------------------------------------------------------------ signatures

    private string Params(MethodModel m, Ctx ctx, TypeModel t, ImmutableArray<ParamModel>? subset = null, bool explicitImpl = false)
    {
        var ps = subset ?? m.Params;
        int lastRequired = -1;
        for (int i = 0; i < ps.Length; i++) if (!ps[i].HasDefault && !ps[i].Params) lastRequired = i;
        var parts = new List<string>();
        var names = new HashSet<string>();
        for (int i = 0; i < ps.Length; i++)
        {
            var p = ps[i];
            string mod = "";
            if (i == 0 && m.Extension && subset == null) mod = "this ";
            TypeSig type = p.Type;
            if (type is ByRefSig r) { mod += p.Out ? "out " : r.ReadOnly ? "in " : "ref "; type = r.Element; }
            if (p.Params && i == ps.Length - 1 && type is ArraySig) mod += "params ";
            string name = Identifier.Source(p.Name);
            while (!names.Add(name)) name += "_";
            string def = p.HasDefault && i > lastRequired && p.Type is not ByRefSig && !explicitImpl ? " = " + Literal(p.Default, type, ctx, parameter: true) : "";
            parts.Add($"{mod}{T(type, ctx)} {name}{def}");
        }
        return string.Join(", ", parts);
    }

    /// <summary>Arguments forwarding the parameters as they are declared (ref/out/in kept).</summary>
    private static string Args(IEnumerable<ParamModel> ps)
    {
        var names = new HashSet<string>();
        return string.Join(", ", ps.Select(p =>
        {
            string name = Identifier.Source(p.Name);
            while (!names.Add(name)) name += "_";
            return (p.Type is ByRefSig r ? (p.Out ? "out " : r.ReadOnly ? "in " : "ref ") : "") + name;
        }));
    }

    private string RefReturn(TypeSig s, Ctx ctx) => s is ByRefSig r ? (r.ReadOnly ? "ref readonly " : "ref ") + T(r.Element, ctx) : T(s, ctx);

    private static bool HasPointer(TypeSig s) => s switch
    {
        PointerSig => true,
        ArraySig a => HasPointer(a.Element),
        ByRefSig r => HasPointer(r.Element),
        NamedSig n => n.Args.Any(HasPointer),
        _ => false,
    };

    private static bool Unsafe(MethodModel m) => HasPointer(m.Return) || m.Params.Any(p => HasPointer(p.Type));

    private static readonly Dictionary<string, string> Keywords = new()
    {
        ["System.Void"] = "void", ["System.Boolean"] = "bool", ["System.Char"] = "char", ["System.SByte"] = "sbyte",
        ["System.Byte"] = "byte", ["System.Int16"] = "short", ["System.UInt16"] = "ushort", ["System.Int32"] = "int",
        ["System.UInt32"] = "uint", ["System.Int64"] = "long", ["System.UInt64"] = "ulong", ["System.Single"] = "float",
        ["System.Double"] = "double", ["System.Decimal"] = "decimal", ["System.Object"] = "object", ["System.String"] = "string",
        ["System.IntPtr"] = "nint", ["System.UIntPtr"] = "nuint",
    };

    private static string Keyword(string name) => Keywords.TryGetValue(name, out var k) ? k : "global::" + name;

    /// <summary>A type reference in C# syntax, fully qualified.</summary>
    private string T(TypeSig s, Ctx ctx)
    {
        switch (s)
        {
            case NamedSig n:
            {
                if (n.Args.Length == 0 && Keywords.TryGetValue(n.Name, out var kw)) return kw;
                var segments = n.Name.Split('+');
                var sb = new StringBuilder("global::");
                int argIndex = 0;
                for (int i = 0; i < segments.Length; i++)
                {
                    string seg = segments[i];
                    int tick = seg.LastIndexOf('`');
                    int arity = tick > 0 && int.TryParse(seg.AsSpan(tick + 1), out var a) ? a : 0;
                    string plain = tick > 0 ? seg[..tick] : seg;
                    if (i > 0) sb.Append('.');
                    if (i == 0)
                    {
                        int dot = plain.LastIndexOf('.');
                        sb.Append(dot < 0 ? Identifier.Source(plain) : plain[..(dot + 1)] + Identifier.Source(plain[(dot + 1)..]));
                    }
                    else sb.Append(Identifier.Source(plain));
                    if (arity > 0 && n.Args.Length >= argIndex + arity)
                    {
                        sb.Append('<').Append(string.Join(", ", n.Args.Skip(argIndex).Take(arity).Select(x => T(x, ctx)))).Append('>');
                        argIndex += arity;
                    }
                }
                return sb.ToString();
            }
            case ArraySig:
            {
                var ranks = new StringBuilder();
                TypeSig cur = s;
                while (cur is ArraySig arr) { ranks.Append('[').Append(',', Math.Max(0, arr.Rank - 1)).Append(']'); cur = arr.Element; }
                return T(cur, ctx) + ranks;
            }
            case PointerSig p: return T(p.Element, ctx) + "*";
            case ByRefSig r: return T(r.Element, ctx); // callers render ref/out/in themselves
            case GenericParamSig g:
                var list = g.OfMethod ? ctx.MethodParams : ctx.TypeParams;
                return g.Index < list.Length ? list[g.Index] : $"T{g.Index}";
            default: return "object";
        }
    }

    // ------------------------------------------------------------------ literals

    private string Literal(object? value, TypeSig type, Ctx ctx, bool parameter = false)
    {
        bool primitive = type is NamedSig n && Keywords.ContainsKey(n.Name) && n.Args.Length == 0;
        if (value == null) return parameter ? "default" : primitive || type is not NamedSig ? "null" : "default";
        if (value is string s) return StringLiteral(s);
        if (value is bool b) return b ? "true" : "false";
        if (value is char c) return $"'\\u{(int)c:X4}'";
        string num = NumberLiteral(value);
        // A constant converts implicitly to T?, but a cast to T? is not a constant: cast to T instead.
        if (type is NamedSig { Name: "System.Nullable`1" } nullable) type = nullable.Args[0];
        primitive = type is NamedSig n2 && Keywords.ContainsKey(n2.Name) && n2.Args.Length == 0;
        return primitive && TypeMatches(type, value) ? num : $"({T(type, ctx)})({num})";
    }

    private static bool TypeMatches(TypeSig type, object value) => ((NamedSig)type).Name switch
    {
        "System.Object" => false,
        _ => true,
    };

    private static string NumberLiteral(object? v) => v switch
    {
        null => "0",
        int i => i.ToString(CultureInfo.InvariantCulture),
        uint u => u.ToString(CultureInfo.InvariantCulture) + "u",
        long l => l.ToString(CultureInfo.InvariantCulture) + "L",
        ulong ul => ul.ToString(CultureInfo.InvariantCulture) + "UL",
        short sh => sh.ToString(CultureInfo.InvariantCulture),
        ushort us => us.ToString(CultureInfo.InvariantCulture),
        byte by => by.ToString(CultureInfo.InvariantCulture),
        sbyte sb => sb.ToString(CultureInfo.InvariantCulture),
        char ch => ((int)ch).ToString(CultureInfo.InvariantCulture),
        bool bo => bo ? "1" : "0",
        float f => float.IsNaN(f) ? "float.NaN" : float.IsPositiveInfinity(f) ? "float.PositiveInfinity"
            : float.IsNegativeInfinity(f) ? "float.NegativeInfinity" : f.ToString("R", CultureInfo.InvariantCulture) + "f",
        double d => double.IsNaN(d) ? "double.NaN" : double.IsPositiveInfinity(d) ? "double.PositiveInfinity"
            : double.IsNegativeInfinity(d) ? "double.NegativeInfinity" : d.ToString("R", CultureInfo.InvariantCulture) + "d",
        _ => "0",
    };

    private static string StringLiteral(string s)
    {
        var sb = new StringBuilder("\"");
        foreach (char c in s)
            sb.Append(c switch
            {
                '\\' => "\\\\", '"' => "\\\"", '\0' => "\\0", '\n' => "\\n", '\r' => "\\r", '\t' => "\\t",
                _ when c < 0x20 || char.IsSurrogate(c) || c > 0x7E => $"\\u{(int)c:X4}",
                _ => c.ToString(),
            });
        return sb.Append('"').ToString();
    }
